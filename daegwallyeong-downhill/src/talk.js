export function lineCount() {
  let n = 0;
  const walk = (v) => { if (typeof v === 'string') n++; else if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === 'object') Object.values(v).forEach(walk); };
  walk(L);
  return n;
}

export class TalkDirector {
  /** ctx: { stageId, weather, tries, wins, spent, hp, sticker } */
  constructor(ctx) {
    this.ctx = ctx; this.bags = new Map(); this.t = 0; this.last = -9; this.next = 3.2; this.once = new Set(); this.count = 0;
  }
  _bag(key, arr) {
    let b = this.bags.get(key);
    if (!b || !b.length) { b = arr.slice(); for (let i = b.length - 1; i > 0; i--) { const j = (Math.random() * (i + 1)) | 0; [b[i], b[j]] = [b[j], b[i]]; } this.bags.set(key, b); }
    return b.pop();
  }
  _fmt(s) { const c = this.ctx; return s.replace('{n}', c.tries + 1).replace('{won}', won(c.spent)).replace('{hp}', c.hp); }
  pick(cat, handicap) {
    let arr = L[cat], key = cat;
    if (cat === 'start') { arr = L.start[handicap]; key = 'start' + handicap; }
    else if (cat === 'by') { arr = L.by[handicap]; key = 'by' + handicap; }
    else if (cat === 'weather') { arr = L.weather[this.ctx.weather]; key = 'w'; }
    else if (cat === 'place') { arr = L.place[this.ctx.stageId]; key = 'p'; }
    if (!arr || !arr.length) return null;
    return this._fmt(this._bag(key, arr));
  }
  /** 사건이 났을 때. 직전 대사와 너무 붙으면 건너뛴다. */
  event(cat, handicap, force = false) {
    if (!force && this.t - this.last < 2.4) return null;
    const line = this.pick(cat, handicap);
    if (line) { this.last = this.t; this.next = this.t + 4.3 + Math.random() * 1.8 + line.length * 0.02; this.count++; }
    return line;
  }
  /** 매 프레임. st: { gap(할배−나, m), progress, hearts, handicap } */
  tick(dt, st) {
    this.t += dt;
    if (this.t < this.next) return null;
    const c = this.ctx, w = [];
    const add = (cat, weight, onceKey) => { if (onceKey && this.once.has(onceKey)) return; w.push([cat, weight, onceKey]); };
    add('by', 3.2); add('idle', 2.2);
    if (st.gap > 35) add('farBehind', 3.5); else if (st.gap > 1 && st.gap < 14) add('closeBehind', 3); else if (st.gap < -3) add('playerLeads', 3.2);
    if (st.progress > 0.84) add('final', 6, 'final');
    if (c.tries - c.wins >= 2 && c.wins === 0) add('loseStreak', 2, 'streak');
    if (c.spent > 1500000) add('rich', 1.6, 'rich' + ((this.t / 30) | 0)); else if (c.spent < 200000) add('stock', 1.2, 'stock');
    add('weather', 1.2, 'weather'); add('place', 1.6, 'place' + ((this.t / 40) | 0));
    if (st.hearts <= 1) add('heartsLow', 2.5, 'hearts');
    if (c.sticker) add('sticker', 2, 'sticker');
    let sum = 0; for (const e of w) sum += e[1];
    let r = Math.random() * sum, pickE = w[0];
    for (const e of w) { r -= e[1]; if (r <= 0) { pickE = e; break; } }
    if (pickE[2]) this.once.add(pickE[2]);
    return this.event(pickE[0], st.handicap, true) || this.event('idle', st.handicap, true);
  }
}
